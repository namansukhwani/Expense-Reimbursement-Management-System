#!/usr/bin/env node

const DEFAULT_BASE_URL = 'http://localhost:3000/api/v1';
const PASSWORD = process.env.SMOKE_PASSWORD || 'secret123';

const baseUrl = (process.env.API_BASE_URL || DEFAULT_BASE_URL).replace(/\/$/, '');

let employeeAuth;
let managerAuth;
let adminAuth;

function log(message) {
  process.stdout.write(`${message}\n`);
}

function assert(condition, message) {
  if (!condition) {
    throw new Error(message);
  }
}

async function parseResponse(response) {
  const contentType = response.headers.get('content-type') || '';
  if (contentType.includes('application/json')) {
    return response.json();
  }
  return response.arrayBuffer();
}

async function request(method, path, { token, body, formData, expected = [200, 201] } = {}) {
  const headers = {};
  const options = { method, headers };

  if (token) {
    headers.Authorization = `Bearer ${token}`;
  }

  if (body !== undefined) {
    headers['Content-Type'] = 'application/json';
    options.body = JSON.stringify(body);
  }

  if (formData) {
    options.body = formData;
  }

  let response;
  try {
    response = await fetch(`${baseUrl}${path}`, options);
  } catch (error) {
    throw new Error(
      `Could not reach ${baseUrl}. Start the API with "npm run start:dev" and confirm the database is migrated/seeded.\n${error.message}`,
    );
  }
  const payload = await parseResponse(response);

  if (!expected.includes(response.status)) {
    const detail =
      payload instanceof ArrayBuffer
        ? `${payload.byteLength} bytes`
        : JSON.stringify(payload, null, 2);
    throw new Error(`${method} ${path} returned ${response.status}\n${detail}`);
  }

  return payload;
}

async function login(email) {
  const payload = await request('POST', '/auth/login', {
    body: { email, password: PASSWORD },
  });

  assert(payload.success, `Login failed for ${email}`);
  assert(payload.data.accessToken, `Missing access token for ${email}`);
  assert(payload.data.refreshToken, `Missing refresh token for ${email}`);
  return payload.data;
}

function firstItem(payload, label) {
  const item = payload.data?.[0];
  assert(item?.id, `No ${label} records found. Run npm run seed first.`);
  return item;
}

async function main() {
  log(`API smoke flow starting against ${baseUrl}`);

  employeeAuth = await login('employee@payoneer.com');
  managerAuth = await login('manager@payoneer.com');
  adminAuth = await login('admin@payoneer.com');
  log('Auth login OK for employee, manager, and admin');

  const refreshed = await request('POST', '/auth/refresh', {
    token: employeeAuth.refreshToken,
  });
  assert(refreshed.data.accessToken, 'Refresh did not return a new access token');

  const employeeProfile = await request('GET', '/auth/me', {
    token: employeeAuth.accessToken,
  });
  assert(employeeProfile.data.email === 'employee@payoneer.com', 'Unexpected /auth/me user');
  log('Auth refresh and profile OK');

  const settings = await request('GET', '/settings', { token: adminAuth.accessToken });
  assert(Array.isArray(settings.data), 'Settings response should contain data array');

  const departments = await request('GET', '/departments?page=1&limit=10', {
    token: adminAuth.accessToken,
  });
  const department = firstItem(departments, 'department');
  await request('GET', `/departments/${department.id}`, { token: adminAuth.accessToken });

  const exchangeRates = await request('GET', '/exchange-rates?page=1&limit=10', {
    token: adminAuth.accessToken,
  });
  assert(Array.isArray(exchangeRates.data), 'Exchange rates response should contain data array');

  const categories = await request('GET', '/categories?page=1&limit=10', {
    token: employeeAuth.accessToken,
  });
  const category = firstItem(categories, 'category');
  await request('GET', '/categories/active', { token: employeeAuth.accessToken });
  await request('GET', `/categories/${category.id}`, { token: employeeAuth.accessToken });
  log(`Configuration APIs OK; using category "${category.name}"`);

  const datePrefix = new Date().toISOString().slice(0, 10);
  const expenseInputs = [
    {
      title: `Smoke flow taxi ${Date.now()}`,
      categoryId: category.id,
      amount: 42.5,
      currency: 'USD',
      expenseDate: datePrefix,
      notes: 'Generated by test/api-smoke-flow.js',
      isReimbursable: true,
    },
    {
      title: `Smoke flow meal ${Date.now()}`,
      categoryId: category.id,
      amount: 28.75,
      currency: 'USD',
      expenseDate: datePrefix,
      notes: 'Generated by test/api-smoke-flow.js',
      isReimbursable: true,
    },
  ];

  const createdExpenses = [];
  for (const expenseInput of expenseInputs) {
    const created = await request('POST', '/expenses', {
      token: employeeAuth.accessToken,
      body: expenseInput,
      expected: [200, 201],
    });
    assert(created.data.id, 'Created expense is missing id');
    createdExpenses.push(created.data);
  }
  log(`Created ${createdExpenses.length} expenses`);

  const firstExpense = createdExpenses[0];
  const updatedExpense = await request('PATCH', `/expenses/${firstExpense.id}`, {
    token: employeeAuth.accessToken,
    body: { notes: 'Updated before claim creation by smoke script' },
  });
  assert(updatedExpense.data.notes.includes('Updated'), 'Expense update did not persist');

  const receipt = new FormData();
  receipt.append(
    'receipt',
    new Blob(['smoke receipt\n'], { type: 'text/plain' }),
    'smoke-receipt.txt',
  );
  await request('POST', `/expenses/${firstExpense.id}/receipt`, {
    token: employeeAuth.accessToken,
    formData: receipt,
  });
  const downloadedReceipt = await request('GET', `/expenses/${firstExpense.id}/receipt`, {
    token: employeeAuth.accessToken,
  });
  assert(downloadedReceipt.byteLength > 0, 'Receipt download returned an empty file');
  await request('DELETE', `/expenses/${firstExpense.id}/receipt`, {
    token: employeeAuth.accessToken,
  });

  await request('GET', '/expenses?page=1&limit=10', { token: employeeAuth.accessToken });
  await request('GET', `/expenses/${firstExpense.id}`, { token: employeeAuth.accessToken });
  const unattached = await request('GET', '/expenses/unattached', {
    token: employeeAuth.accessToken,
  });
  const unattachedIds = new Set(unattached.data.map((expense) => expense.id));
  for (const expense of createdExpenses) {
    assert(unattachedIds.has(expense.id), `Expense ${expense.id} is not available for claim creation`);
  }
  log('Expense APIs OK, including receipt upload/download/delete');

  const claim = await request('POST', '/claims', {
    token: employeeAuth.accessToken,
    body: {
      expenseIds: createdExpenses.map((expense) => expense.id),
      employeeNotes: 'Smoke claim generated by test/api-smoke-flow.js',
    },
    expected: [200, 201],
  });
  assert(claim.data.id, 'Created claim is missing id');
  assert(claim.data.status === 'DRAFT', `Expected DRAFT claim, received ${claim.data.status}`);

  await request('GET', '/claims?page=1&limit=10', { token: employeeAuth.accessToken });
  const claimDetails = await request('GET', `/claims/${claim.data.id}`, {
    token: employeeAuth.accessToken,
  });
  assert(claimDetails.data.expenses.length === createdExpenses.length, 'Claim does not include all expenses');

  const submitted = await request('POST', `/claims/${claim.data.id}/submit`, {
    token: employeeAuth.accessToken,
  });
  assert(submitted.data.status === 'SUBMITTED', `Expected SUBMITTED claim, received ${submitted.data.status}`);
  log(`Claim ${submitted.data.claimNumber || submitted.data.id} created and submitted`);

  const pendingApprovals = await request('GET', '/approvals/pending?page=1&limit=10', {
    token: managerAuth.accessToken,
  });
  assert(
    pendingApprovals.data.some((pendingClaim) => pendingClaim.id === claim.data.id),
    'Submitted claim was not visible in manager pending approvals',
  );
  
  log('Approving claim by manager to test termination state');
  const approved = await request('POST', `/approvals/claims/${claim.data.id}/approve`, {
    token: managerAuth.accessToken,
    body: { comment: 'Approved via API smoke test flow' },
  });
  assert(approved.data.status === 'APPROVED', `Expected APPROVED claim, received ${approved.data.status}`);
  log(`Claim ${claim.data.id} successfully approved`);

  const historyApprovals = await request('GET', '/approvals/history?page=1&limit=10', {
    token: managerAuth.accessToken,
  });
  assert(
    historyApprovals.data.some(
      (historyAction) =>
        historyAction.claimId === claim.data.id ||
        (historyAction.claim && historyAction.claim.id === claim.data.id),
    ),
    'Approved claim was not visible in manager approval history',
  );

  await request('GET', '/audit-logs?page=1&limit=10', {
    token: adminAuth.accessToken,
  });
  const history = await request('GET', `/audit-logs/claims/${claim.data.id}/history`, {
    token: adminAuth.accessToken,
  });
  assert(Array.isArray(history.data), 'Claim history response should contain data array');

  log('Approval, termination, and audit APIs OK');
  log('API smoke flow completed successfully');
}

main().catch((error) => {
  process.stderr.write(`\nAPI smoke flow failed:\n${error.stack || error.message}\n`);
  process.exit(1);
});
